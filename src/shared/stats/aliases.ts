/** How phrases compare: lower case, apostrophes dropped, anything else not a letter or digit a space. */
export function phraseKey(text: string): string {
  return text
    .toLowerCase()
    .replace(/['’]/g, '')
    .replace(/[^a-z0-9]+/g, ' ')
    .trim()
}
